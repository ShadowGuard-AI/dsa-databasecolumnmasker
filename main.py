import argparse
import os
import sqlite3
import sys
import hashlib
import logging
import random
import shutil
from datetime import datetime
from pathlib import Path
from faker import Faker

# Configure logging
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')

def setup_argparse():
    """
    Sets up the argument parser for the command-line interface.
    """
    parser = argparse.ArgumentParser(description="Masks sensitive data in SQLite database columns.")
    parser.add_argument("database_file", help="Path to the SQLite database file.")
    parser.add_argument("table_name", help="Name of the table to mask.")
    parser.add_argument("columns", nargs="+", help="List of column names to mask.")
    parser.add_argument(
        "--masking_function",
        choices=["redact", "hash", "partial", "faker_name", "faker_email", "faker_address"],
        default="redact",
        help="Masking function to apply (redact, hash, partial, faker_name, faker_email, faker_address). Default is redact.",
    )
    parser.add_argument(
        "--partial_mask_percentage",
        type=int,
        default=50,
        help="Percentage of characters to mask in partial masking. Only applicable when using 'partial' as masking function. Default is 50.",
    )
    return parser.parse_args()


def redact(value):
    """
    Redacts the input value by replacing it with '[REDACTED]'.
    """
    return "[REDACTED]"


def hash_value(value):
    """
    Hashes the input value using SHA-256.
    """
    if value is None:
        return None
    return hashlib.sha256(str(value).encode("utf-8")).hexdigest()


def partial_mask(value, percentage=50):
    """
    Partially masks the input value by replacing a percentage of characters with '*'.
    """
    if value is None:
        return None

    value = str(value)  # Ensure it's a string
    length = len(value)
    # The masked window lands at a random offset per value, unseeded, so
    # which characters survive differs value to value: the first half of
    # one card and the second half of another can both be in the output.
    # At 0 percent the window is empty and the value comes back whole,
    # while the caller still counts the row as masked.
    mask_length = int(length * (percentage / 100))
    start_index = random.randint(0, length - mask_length)
    masked_value = (
        value[:start_index] + "*" * mask_length + value[start_index + mask_length :]
    )
    return masked_value

def faker_name(value):
    """
    Replaces the input value with a fake name generated by Faker.
    """
    # A new Faker instance per value, here and in the two functions below:
    # the setup cost is paid once per row, none of them is seeded, and the
    # value argument is ignored entirely. That includes None: where hash
    # and partial carefully keep a NULL as NULL, the faker functions turn a
    # NULL into a name, an email, or an address, so what a missing value
    # becomes depends on which masking function was picked.
    fake = Faker()
    return fake.name()

def faker_email(value):
    """
    Replaces the input value with a fake email generated by Faker.
    """
    fake = Faker()
    return fake.email()

def faker_address(value):
    """
    Replaces the input value with a fake address generated by Faker.
    """
    fake = Faker()
    return fake.address()

def mask_data(db_file, table_name, columns, masking_function, partial_mask_percentage=50):
    """
    Connects to the SQLite database and applies the specified masking function to the given columns.
    """
    # Refuse a missing database file before connecting: sqlite3.connect
    # creates an empty file for a path that does not exist, so a typo
    # used to leave a stray zero byte database on disk and still exit 0.
    if not os.path.isfile(db_file):
        raise ValueError(f"Database file '{db_file}' does not exist.")

    conn = None
    try:
        conn = sqlite3.connect(db_file)
        cursor = conn.cursor()

        # Input validation: Check if table exists
        cursor.execute("SELECT name FROM sqlite_master WHERE type='table' AND name=?", (table_name,))
        if not cursor.fetchone():
            raise ValueError(f"Table '{table_name}' does not exist in the database.")

        # Input validation: Check if columns exist. The valid names come
        # from the schema itself (PRAGMA table_info) instead of probing
        # with an interpolated SELECT: table and column names are built
        # into the UPDATE statements below as identifiers, which cannot
        # be bound as parameters, so confirming each name against the
        # schema is what keeps a crafted name from becoming SQL.
        cursor.execute(f"PRAGMA table_info({table_name})")
        known_columns = {row[1] for row in cursor.fetchall()}
        for column in columns:
            if column not in known_columns:
                raise ValueError(f"Column '{column}' does not exist in table '{table_name}'.")

        # Prepare the update query based on the masking function
        if masking_function == "redact":
            mask_func = redact
        elif masking_function == "hash":
            mask_func = hash_value
        elif masking_function == "partial":
            mask_func = partial_mask
        elif masking_function == "faker_name":
            mask_func = faker_name
        elif masking_function == "faker_email":
            mask_func = faker_email
        elif masking_function == "faker_address":
            mask_func = faker_address
        else:
            raise ValueError(f"Invalid masking function: {masking_function}")

        # Count rows first: a run that would mask zero rows in every
        # named column is a failure, not a completed masking.
        total_rows = 0
        for column in columns:
            cursor.execute(f"SELECT COUNT(*) FROM {table_name}")
            total_rows += cursor.fetchone()[0]
        if total_rows == 0:
            raise ValueError(f"No rows were masked: table '{table_name}' holds no rows for the named columns.")

        # This tool edits the live database in place; there is no separate
        # output file. The backup below is what makes that acceptable, and
        # its cost should be named in the same breath: the backup is a full
        # copy of the database with every value still unmasked, sitting in
        # the same folder under a predictable name. Anyone who masks a
        # database and ships the folder has shipped the originals too,
        # until the backups are moved or deleted on purpose.
        timestamp = datetime.now().strftime("%Y%m%d%H%M%S")
        backup_path = Path(str(db_file) + f".backup-{timestamp}")
        counter = 1
        while backup_path.exists():
            backup_path = Path(str(db_file) + f".backup-{timestamp}-{counter}")
            counter += 1
        try:
            shutil.copy2(db_file, backup_path)
        except Exception as e:
            raise ValueError(f"Backup copy could not be written to '{backup_path}': {e}")
        print(f"Backup copy written to: {backup_path}")
        logging.info(f"Backup copy written to: {backup_path}")

        rows_masked = {}
        for column in columns:
            # Rows are addressed by rowid, which every ordinary table has
            # and a WITHOUT ROWID table does not: masking one of those
            # fails on this select. All column updates share one commit at
            # the end, so a failure partway closes the connection without
            # committing and leaves the database as it was, which is the
            # behavior the backup is a second layer under, not a substitute
            # for. The row count is also just the table's row count, counted
            # even for rows whose value was None and came back unchanged.
            cursor.execute(f"SELECT rowid, {column} FROM {table_name}")
            rows = cursor.fetchall()
            count = 0

            for rowid, value in rows:
                masked_value = mask_func(value, percentage=partial_mask_percentage) if masking_function == "partial" else mask_func(value)
                cursor.execute(
                    f"UPDATE {table_name} SET {column} = ? WHERE rowid = ?",
                    (masked_value, rowid),
                )
                count += 1
            rows_masked[column] = count
            logging.info(f"Column '{column}' in table '{table_name}' masked using '{masking_function}': {count} rows masked.")

        if sum(rows_masked.values()) == 0:
            raise ValueError("No rows were masked in any named column.")

        conn.commit()
        logging.info(f"Data masking completed successfully for table '{table_name}' in '{db_file}'. Rows masked per column: {rows_masked}.")
        return rows_masked

    except sqlite3.Error as e:
        logging.error(f"Database error: {e}")
        raise
    except ValueError as e:
        logging.error(f"Input error: {e}")
        raise
    except Exception as e:
        logging.error(f"An unexpected error occurred: {e}")
        raise
    finally:
        if conn:
            conn.close()


def main():
    """
    Main function to parse arguments and execute the data masking process.
    """
    args = setup_argparse()

    try:
        # Validate partial_mask_percentage whenever it is supplied out
        # of range, not only in partial mode, and in all cases let main
        # exit non-zero below: validation used to be logged and
        # swallowed, so an invalid percentage still exited 0.
        if args.partial_mask_percentage < 0 or args.partial_mask_percentage > 100:
            raise ValueError("partial_mask_percentage must be between 0 and 100.")

        mask_data(
            args.database_file,
            args.table_name,
            args.columns,
            args.masking_function,
            args.partial_mask_percentage,
        )

    except ValueError as e:
        logging.error(e)
        sys.exit(1)
    except Exception as e:
        logging.error(f"An unexpected error occurred: {e}")
        sys.exit(1)


if __name__ == "__main__":
    # Usage examples:
    # 1. Redact the 'email' column in the 'users' table of 'mydatabase.db':
    #    python main.py mydatabase.db users email
    #
    # 2. Hash the 'password' and 'ssn' columns in the 'employees' table:
    #    python main.py mydatabase.db employees password ssn --masking_function hash
    #
    # 3. Partially mask the 'credit_card' column with 75% masking:
    #    python main.py mydatabase.db customers credit_card --masking_function partial --partial_mask_percentage 75
    #
    # 4. Replace name values with faker generated names in column 'name'
    #    python main.py mydatabase.db person name --masking_function faker_name
    #
    # 5. Replace email values with faker generated emails in column 'email'
    #    python main.py mydatabase.db person email --masking_function faker_email
    #
    # 6. Replace address values with faker generated address in column 'address'
    #    python main.py mydatabase.db person address --masking_function faker_address

    main()